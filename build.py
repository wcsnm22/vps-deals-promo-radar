# ------------------------------------------------------------------ 主流程

def main() -> int:
    global ASSET_V
    config = load_config()
    site_cfg = config["site"]
    payload = json.loads(DATA_PATH.read_text(encoding="utf-8"))

    base_url = "https://" + site_cfg["domain"].rstrip("/")
    site = {
        "brand": site_cfg.get("brand", "vps-deals"),
        "title": site_cfg.get("title", "VPS Deals Radar"),
        "tagline": site_cfg.get("tagline", ""),
        "locale": site_cfg.get("locale", "en-US"),
        "domain": site_cfg["domain"],
        "base_url": base_url,
        "og_image": site_cfg.get("og_image", f"{base_url}/og.png"),
        "repo_url": site_cfg.get("repo", ""),
    }
    offers = payload["offers"]
    variants: dict[tuple, int] = {}
    offers, variants = collapse_offers(offers)
    providers = payload["providers"]
    by_name = {row["name"]: row for row in providers}
    global PROVIDERS_CTX
    PROVIDERS_CTX = providers
    generated_at = payload["generated_at"]

    SITE_DIR.mkdir(parents=True, exist_ok=True)
    (SITE_DIR / "provider").mkdir(exist_ok=True)
    (SITE_DIR / "deal").mkdir(exist_ok=True)
    (SITE_DIR / "assets").mkdir(exist_ok=True)
    (SITE_DIR / "guide").mkdir(exist_ok=True)
    (SITE_DIR / "downloads").mkdir(exist_ok=True)

    ASSET_V = re.sub(r"[^0-9A-Za-z]", "", generated_at) or "0"
    VERIFY["gsc"] = (site_cfg.get("gsc_verification") or "").strip()
    VERIFY["ga4"] = (site_cfg.get("ga4_measurement_id") or "").strip()
    if VERIFY["ga4"] and not re.fullmatch(r"G-[A-Z0-9]{4,}", VERIFY["ga4"]):
        raise SystemExit(f'ga4_measurement_id 看起来不是 GA4 衡量 ID：{VERIFY["ga4"]!r}（应形如 G-XXXXXXXXXX）')
    asset_paths = []
    if ASSET_DIR.exists():
        for asset in sorted(ASSET_DIR.iterdir()):
            if asset.is_file():
                (SITE_DIR / "assets" / asset.name).write_text(asset.read_text(encoding="utf-8"), encoding="utf-8")
                asset_paths.append(f"/assets/{asset.name}")

    # 社交分享大图（真 PNG，构建时用标准库生成；og:image 指向它，不再是一条坏链接）
    build_og_image(site, SITE_DIR / "og.png")
    asset_paths.append("/og.png")

    # 指南清单提前载入：about 页要引用当期篇数，页脚导航也要用
    guides = json.loads(GUIDES_PATH.read_text(encoding="utf-8")) if GUIDES_PATH.exists() else []

    # T5 套图：把抓到的价格画成 SVG（纯文本、零依赖），文件名由数据决定。
    chart_names = chart_assets.build_all(offers, SITE_DIR / "assets")
    asset_paths += [f"/assets/{name}" for name in chart_names]

    written = []
    for name, html in {
        "index.html": build_index(site, offers, providers, generated_at),
        "compare.html": build_compare(site, offers, providers, generated_at),
        "about.html": build_about(site, providers, generated_at, offers, len(guides)),
        "methodology.html": build_methodology(site, providers, generated_at),
        "privacy.html": build_privacy(site, providers, generated_at),
        "contact.html": build_contact(site, providers, generated_at),
        "404.html": build_404(site, providers, generated_at),
    }.items():
        (SITE_DIR / name).write_text(html, encoding="utf-8")
        written.append(name)

    grouped = group_offers(offers)
    for provider in providers:
        html = build_provider(site, provider, grouped.get(provider["name"], []), generated_at)
        path = SITE_DIR / "provider" / f"{slugify(provider['name'])}.html"
        path.write_text(html, encoding="utf-8")
        written.append(f"provider/{path.name}")

    for offer in offers:
        html = build_deal(site, offer, generated_at,
                            variants.get((offer["provider"], offer["title"].lower()), 1),
                            grouped.get(offer["provider"], []))
        path = SITE_DIR / "deal" / f"{offer_slug(offer)}.html"
        path.write_text(html, encoding="utf-8")
        written.append(f"deal/{path.name}")

    # 厂商改型号或改套餐名之后，旧 slug 的 deal 页会变成孤儿页：线上已被 _worker.js
    # 的白名单判 404，文件却还留在 site/ 里被每次部署一起上传。deal 页全部由本次 offers
    # 生成，所以直接和本次产出的集合对齐；和指南那段的清理保持同一套做法。
    deal_keep = {f"{offer_slug(offer)}.html" for offer in offers}
    for stale in sorted((SITE_DIR / "deal").glob("*.html")):
        if stale.name not in deal_keep:
            stale.unlink()
            written.append(f"removed stale deal/{stale.name}")

    # 厂商从 site.ilang 删掉之后，它的 provider 页同样会变成孤儿页（deal 页上面清了，
    # provider 页当初漏了，自测 TEST2 抓到过）：和本次 providers 集合对齐，同一套做法。
    provider_keep = {f"{slugify(provider['name'])}.html" for provider in providers}
    for stale in sorted((SITE_DIR / "provider").glob("*.html")):
        if stale.name not in provider_keep:
            stale.unlink()
            written.append(f"removed stale provider/{stale.name}")

    # 可下载的比价表：三家里没有任何一家提供这种文件，这是这个词最集中的缺口。
    csv_body, csv_rows = build_unit_price_csv(offers)
    (SITE_DIR / "downloads" / "unit-price.csv").write_text(csv_body, encoding="utf-8")

    # 指南栏：每篇只补一个缺口，内容由 data/guides.json 提供，渲染是确定性的。
    # 清掉已经不存在的指南页，否则旧日期的页面会一直留在线上的目录里变成孤儿页。
    # 只删"带日期后缀的自动页"（csv-YYYY-MM-DD-n / unitprice-... / steps-...），手写页不碰。
    keep = {f'{guide["slug"]}.html' for guide in guides}
    for stale in sorted((SITE_DIR / "guide").glob("*.html")):
        if stale.name in keep:
            continue
        if re.match(r"^(csv|unitprice|steps)-\d{4}-\d{2}-\d{2}-\d+\.html$", stale.name):
            stale.unlink()
            written.append(f"removed stale guide/{stale.name}")
    (SITE_DIR / "guide.html").write_text(
        build_guide_index(site, guides, offers, providers, generated_at), encoding="utf-8"
    )
    written.append("guide.html")
    for guide in guides:
        html = build_guide(site, guide, offers, providers, generated_at, guides)
        path = SITE_DIR / "guide" / f'{guide["slug"]}.html'
        path.write_text(html, encoding="utf-8")
        written.append(f"guide/{path.name}")

    urls = [home_url(site), compare_url(site)]
    urls += [f"{base_url}/about", f"{base_url}/methodology", f"{base_url}/privacy", f"{base_url}/contact"]
    urls += [provider_page(site, row["name"]) for row in providers]
    urls += [deal_page(site, offer) for offer in offers]
    # 可下载的 CSV 也进 sitemap：它是站上唯一的可下载资产页，值得被抓到
    urls += [f"{base_url}/downloads/unit-price.csv"]
    urls += [guides_url(site)]
    urls += [guide_page(site, guide) for guide in guides]
    # 指南页用各自的发布日期做 lastmod（自动页有 published），其余用本次构建时间。
    lastmod_for = {guide_page(site, guide): guide.get("published", generated_at) for guide in guides}
    sitemap = ['<?xml version="1.0" encoding="UTF-8"?>', '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for url in urls:
        lastmod = lastmod_for.get(url, generated_at)
        sitemap.append(f"  <url><loc>{escape(url)}</loc><lastmod>{escape(lastmod)}</lastmod></url>")
    sitemap.append("</urlset>")
    (SITE_DIR / "sitemap.xml").write_text("\n".join(sitemap) + "\n", encoding="utf-8")
    (SITE_DIR / "robots.txt").write_text(
        f"User-agent: *\nAllow: /\n\nSitemap: {base_url}/sitemap.xml\n", encoding="utf-8"
    )
    # 合法路径白名单：由这次构建实际写出的页面生成，交给 _worker.js 判 404。
    # 不写死在这里，就不会出现"加了页面却忘了改 404 逻辑"。
    valid_paths = ["/", "/compare", "/about", "/methodology", "/privacy", "/contact", "/sitemap.xml", "/robots.txt", "/guide"]
    valid_paths += asset_paths
    valid_paths.append("/downloads/unit-price.csv")
    valid_paths += [f"/provider/{slugify(row['name'])}" for row in providers]
    valid_paths += [f"/deal/{offer_slug(offer)}" for offer in offers]
    valid_paths += [f'/guide/{guide["slug"]}' for guide in guides]
    (SITE_DIR / "_worker.js").write_text(
        WORKER_TEMPLATE.replace("__CANONICAL_HOST__", site_cfg["domain"]).replace(
            "__VALID_PATHS__", json.dumps(valid_paths)
        ),
        encoding="utf-8",
    )

    # 结构化数据自查：Google 对 Product 的必填字段是 name + offers，对 Offer 要 price。
    # 发一个"没有 offers 的 Product"或"没有 price 的 Offer"就是 Search Console 里的硬错误
    # （2026-10-02 GSC 报的就是这一类）。这里在构建时直接拦下，宁可构建失败也不发出去。
    problems = audit_structured_data(SITE_DIR)
    if problems:
        raise SystemExit("结构化数据自查未通过，已阻止构建：\n  " + "\n  ".join(problems[:10]))

    print(
        f"wrote {len(written)} pages + sitemap.xml({len(urls)} urls) + robots.txt + "
        f"_worker.js(301 canonical host, real 404, {len(valid_paths)} allowed paths)"
    )
    print(f"data snapshot {generated_at} | offers {len(offers)} | providers {len(by_name)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
