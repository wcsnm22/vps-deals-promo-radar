def offer_rows(offers: list[dict], site: dict, providers: dict[str, dict], with_provider: bool) -> str:
    rows = []
    for offer in offers:
        price = money(offer.get("price"), offer.get("currency", "USD"))
        price_cell = price if price else '<span class="muted">not published</span>'
        provider_cell = (
            f'<a href="{escape(provider_page(site, offer["provider"]))}">{escape(offer["provider"])}</a>'
            if with_provider
            else ""
        )
        detail = deal_page(site, offer)
        target = affiliate_for(offer, providers)
        rows.append(
            "<tr>"
            f"<td>{provider_cell}</td>"
            f'<td><a href="{escape(detail)}">{escape(offer["title"])}</a></td>'
            f'<td class="price">{price_cell}</td>'
            f'<td><a class="btn" rel="nofollow sponsored noopener" target="_blank" href="{escape(target)}">View on provider</a></td>'
            "</tr>"
        )
    return "\n".join(rows)


def build_index(site: dict, offers: list[dict], providers: list[dict], generated_at: str) -> str:
    grouped = group_offers(offers)
    month = MONTHS[datetime.now(timezone.utc).month - 1]
    priced = [o for o in offers if o.get("price")]
    cheapest = min(priced, key=lambda o: o["price"]) if priced else None
    title = f"{site['title']} — {len(offers)} live VPS deals tracked ({month} {datetime.now(timezone.utc).year})"
    description = (
        f"{len(offers)} VPS plans tracked across {len(grouped)} providers, prices read straight from each "
        f"provider's public page. Updated {generated_at}."
    )
    if cheapest:
        description += f" Cheapest tracked plan: {cheapest['provider']} {cheapest['title']} at {money(cheapest['price'], cheapest.get('currency','USD'))}."

    cards = []
    for provider in providers:
        rows = grouped.get(provider["name"], [])
        if not rows:
            note = provider.get("note") or "no published price found on the source page"
            cards.append(
                f'<div class="card"><h3>{escape(provider["name"])}</h3>'
                f'<p class="muted">Tracked, but {escape(note)}.</p>'
                f'<p><a href="{escape(provider["homepage"])}" rel="nofollow noopener" target="_blank">Official site</a></p></div>'
            )
            continue
        lowest = rows[0]
        cards.append(
            f'<div class="card"><h3><a href="{escape(provider_page(site, provider["name"]))}">'
            f'{escape(provider["name"])}</a></h3>'
            f'<p class="price big">{escape(money(lowest.get("price"), lowest.get("currency","USD")))}</p>'
            f'<p class="muted">from {escape(lowest["title"])} · {len(rows)} plans tracked</p></div>'
        )

    item_list = {
        "@context": "https://schema.org",
        "@type": "ItemList",
        "name": title,
        "itemListElement": [
            {"@type": "ListItem", "position": index + 1,
             "url": deal_page(site, offer), "name": f'{offer["provider"]} {offer["title"]}'}
            for index, offer in enumerate(offers[:50])
        ],
    }
    website = {
        "@context": "https://schema.org",
        "@type": "WebSite",
        "name": site["title"],
        "url": home_url(site),
        "description": description,
    }
    meta = {
        "canonical": home_url(site),
        "locale": site["locale"],
        "title": title,
        "description": description,
        "brand": site["brand"],
        "og_type": "website",
        "og_image": site["og_image"],
    }
    # 第一屏先给答案：最便宜的一档、每 GB 最便宜的一档，都是抓到的数字现算的。
    with_ram = [o for o in priced if o.get("ram_gb")]
    answer_bits = []
    if cheapest:
        answer_bits.append(
            f"Lowest published monthly price right now: {money(cheapest['price'], cheapest.get('currency', 'USD'))} "
            f"({cheapest['provider']} {cheapest['title']})."
        )
    if with_ram:
        best = min(with_ram, key=lambda o: o["price"] / o["ram_gb"])
        answer_bits.append(
            f"Lowest published price per GB of RAM: {best['price'] / best['ram_gb']:.4f} "
            f"{best.get('currency', '')} per GB ({best['provider']} {best['title']}, "
            f"{money(best['price'], best.get('currency', 'USD'))} / {best['ram_gb']} GB)."
        )
    answer_bits.append(
        f"{len(priced)} of {len(offers)} tracked plans publish a price; every row links to the provider page it "
        f"was read from."
    )
    return render(
        template("index.html"),
        {
            "lang": site["locale"],
            "head": head_block(meta, [website, item_list]),
            "nav": nav_block(site, providers),
            "footer": footer_block(site, generated_at),
            "title": escape(title),
            "brand": escape(site["brand"]),
            "tagline": escape(site["tagline"]),
            "answer": escape(" ".join(answer_bits)),
            "chart": _chart_html(
                "per-gb-cheapest.svg",
                alt="Monthly price per GB of RAM for every tracked plan that publishes both numbers",
            ),
            "generated_at": generated_at,
            "cards": "\n".join(cards),
            "rows": offer_rows(offers[:60], site, {}, True),
            "offer_count": str(len(offers)),
            "provider_count": str(len(grouped)),
        },
    )


def build_provider(site: dict, provider: dict, offers: list[dict], generated_at: str) -> str:
    month = MONTHS[datetime.now(timezone.utc).month - 1]
    name = provider["name"]
    priced = [o for o in offers if o.get("price")]
    low = min((o["price"] for o in priced), default=None)
    high = max((o["price"] for o in priced), default=None)
    currency = offers[0].get("currency", provider.get("currency", "USD")) if offers else provider.get("currency", "USD")

    title = f"{name} VPS prices ({month} {datetime.now(timezone.utc).year}) — {len(offers)} plans tracked"
    description = (
        f"{name} VPS plans with prices read from the provider's public page on {generated_at}. "
        + (f"{len(priced)} of {len(offers)} plans publish a price; from {money(low, currency)}." if priced
           else "No price is published in machine-readable form on that page, so this page lists plan names only.")
    )
    # 结构化数据只声明"这页是什么 + 列了哪些套餐"，不声明"我们在卖"。
    # 2026-10-02 改：原来这里发 Product + AggregateOffer。两个问题：
    #   1) 抓不到价格的厂商（DigitalOcean / Hetzner）会发出**没有 offers 的 Product**，
    #      Google 的必填字段就是 name + offers，于是 Search Console 里是实打实的错误；
    #   2) 有价格的厂商会被当成"商家信息"（merchant listing）来校验，而商家信息要求
    #      priceValidUntil / 退货政策 / 运费政策——我们是比价站，这三样一概没有。
    #      为了消警告去编一个 priceValidUntil 是编有效期，仓库的 BOUNDARY 不允许。
    # 所以不再发 Product/Offer，改成 ItemList：我们确实在做的、也确实为真的那件事。
    graphs: list[dict] = [
        {
            "@context": "https://schema.org",
            "@type": "WebPage",
            "name": title,
            "url": provider_page(site, name),
            "description": description,
        }
    ]
    if priced:
        graphs.append(
            {
                "@context": "https://schema.org",
                "@type": "ItemList",
                "name": f"{name} VPS plans tracked with a published price",
                "itemListOrder": "https://schema.org/ItemListOrderAscending",
                "numberOfItems": len(priced),
                "itemListElement": [
                    {
                        "@type": "ListItem",
                        "position": index + 1,
                        "name": f"{name} {offer['title']}",
                        "url": deal_page(site, offer),
                        "description": f"Published price {money(offer['price'], offer.get('currency', currency))}",
                    }
                    for index, offer in enumerate(sorted(priced, key=lambda row: row["price"]))
                ],
            }
        )
    graphs.append(
        {
            "@context": "https://schema.org",
            "@type": "BreadcrumbList",
            "itemListElement": [
                {"@type": "ListItem", "position": 1, "name": site["title"], "item": home_url(site)},
                {"@type": "ListItem", "position": 2, "name": name, "item": provider_page(site, name)},
            ],
        }
    )
    # 两段都由已抓到的数字算出；没有数据就如实说明原因，不填充套话。
    if offers:
        basis_rows = [
            f"<tr><th>Plans readable on the source page</th><td>{len(offers)}</td></tr>",
            f"<tr><th>Of those, publishing a price</th><td>{len(priced)}</td></tr>",
        ]
        with_ram = [o for o in priced if o.get("ram_gb")]
        basis_rows.append(
            f"<tr><th>Publishing a RAM figure beside the price</th><td>{len(with_ram)}</td></tr>")
        basis_rows.append(
            f"<tr><th>Read from</th><td><a href=\"{escape(provider['deals_url'])}\" rel=\"nofollow noopener\" "
            f"target=\"_blank\">{escape(provider['deals_url'])}</a></td></tr>")
        basis_rows.append(f"<tr><th>Read at (UTC)</th><td>{escape(generated_at)}</td></tr>")
        basis = ('<div class="table-shell"><table><tbody>' + "".join(basis_rows) + "</tbody></table></div>")
    else:
        reason = escape(provider.get("note") or "no readable price was found on the source page")
        basis = (
            f'<p>Nothing from {escape(name)} appears in the price table at the moment. The reason recorded by '
            f"the crawler for this run is: <em>{reason}</em>.</p>"
            f'<p class="muted">That is not a judgement about the provider — it means this site could not read a '
            f"published price from "
            f'<a href="{escape(provider["deals_url"])}" rel="nofollow noopener" target="_blank">their page</a> '
            f"on {escape(generated_at)} (UTC), and it does not publish a price it cannot read.</p>"
        )

    ranked = sorted([o for o in priced if o.get("ram_gb")], key=lambda o: o["price"] / o["ram_gb"])
    if ranked:
        per_rows = "".join(
            "<tr>"
            f'<td>{i + 1}</td>'
            f'<td><a href="{escape(deal_page(site, o))}">{escape(o["title"])}</a></td>'
            f'<td class="price">{escape(money(o["price"], o.get("currency", "USD")))}</td>'
            f'<td>{o["ram_gb"]} GB</td>'
            f'<td class="price">{o["price"] / o["ram_gb"]:.4f} {escape(o.get("currency", ""))}</td>'
            "</tr>"
            for i, o in enumerate(ranked)
        )
        per_gb = (
            _chart_html(
                f"per-gb-{slugify(name)}.svg",
                f"monthly-vs-ram-{slugify(name)}.svg",
                alt=f'Monthly price per GB of RAM at {name}, computed from published prices',
            )
            + '<div class="table-shell"><table><thead><tr><th>#</th><th>Plan</th><th>Published price</th>'
            '<th>RAM</th><th>Per GB</th></tr></thead><tbody>' + per_rows + "</tbody></table></div>"
            + f'<p class="muted">{len(ranked)} of {len(priced)} priced plans publish the RAM figure this '
              f'division needs. The rest are left out rather than estimated.</p>'
        )
    else:
        per_gb = (
            '<p class="muted">A price-per-GB figure needs two published numbers: the monthly price and the RAM '
            'figure beside it. No plan from this provider currently publishes both, so no per-unit figure is '
            'shown. See the '
            f'<a href="{escape(site["base_url"])}/methodology">methodology page</a> for how that decision is made.</p>'
        )

    meta = {
        "canonical": provider_page(site, name),
        "locale": site["locale"],
        "title": title,
        "description": description,
        "brand": site["brand"],
        "og_type": "website",
        "og_image": site["og_image"],
    }
    return render(
        template("provider.html"),
        {
            "lang": site["locale"],
            "brand": escape(site["brand"]),
            "head": head_block(meta, graphs),
            "nav": nav_block(site, [provider]),
            "footer": footer_block(site, generated_at),
            "title": escape(title),
            "provider": escape(name),
            "homepage": escape(provider["homepage"]),
            "source_url": escape(provider["deals_url"]),
            "generated_at": generated_at,
            "rows": offer_rows(offers, site, {}, False) or '<tr><td colspan="4" class="muted">No plan with a published price was found on the source page.</td></tr>',
            "low": money(low, currency) if low else "",
            "high": money(high, currency) if high else "",
            "offer_count": str(len(offers)),
            "priced_count": str(len(priced)),
            "note": escape(provider.get("note") or ""),
            "basis": basis,
            "per_gb": per_gb,
            "base_url": escape(site["base_url"]),
        },
    )


def build_deal(site: dict, offer: dict, generated_at: str, variants: int = 1,
               provider_offers: list[dict] | None = None) -> str:
    month = MONTHS[datetime.now(timezone.utc).month - 1]
    currency = offer.get("currency", "USD")
    price_text = money(offer.get("price"), currency)
    title = f'{offer["provider"]} {offer["title"]}' + (f' — {price_text} ({month})' if price_text else f' ({month})')
    description = (
        f'{offer["provider"]} {offer["title"]}'
        + (f' listed at {price_text}' if price_text else ' (no published price found)')
        + f'. Read from {offer["source_url"]} on {offer["fetched_at"]}.'
    )
    # 这一页记录"我们从厂商页面上读到的那个价格"，不是"我们在卖这个东西"。
    # 原来发的是一个裸 Offer（不在 Product 里）：Google 不认这种形状，而且它把页面
    # 拉进商家信息的校验口径，缺 priceValidUntil 就报错。我们抓不到有效期就不写有效期
    # （数据集里 0 条有 valid_until），所以不再发 Offer，改成 WebPage + 这一档的规格。
    schema: dict = {
        "@context": "https://schema.org",
        "@type": "WebPage",
        "name": f'{offer["provider"]} {offer["title"]}',
        "url": deal_page(site, offer),
        "description": description,
    }
    breadcrumb = {
        "@context": "https://schema.org",
        "@type": "BreadcrumbList",
        "itemListElement": [
            {"@type": "ListItem", "position": 1, "name": site["title"], "item": home_url(site)},
            {"@type": "ListItem", "position": 2, "name": offer["provider"],
             "item": provider_page(site, offer["provider"])},
            {"@type": "ListItem", "position": 3, "name": offer["title"], "item": deal_page(site, offer)},
        ],
    }
    meta = {
        "canonical": deal_page(site, offer),
        "locale": site["locale"],
        "title": title,
        "description": description,
        "brand": site["brand"],
        "og_type": "product",
        "og_image": site["og_image"],
    }
    # 三张表全部由已抓到的数字算出；缺输入就如实写"未公布"，不补不估。
    def _row(label: str, value: str) -> str:
        return f"<tr><th>{escape(label)}</th><td>{value}</td></tr>"

    price_value = offer.get("price")
    ram = offer.get("ram_gb")
    vcpu = offer.get("vcpu")
    disk = offer.get("disk_gb")
    currency_code = escape(currency)

    specs_rows = []
    specs_rows.append(_row("Published price",
                           escape(price_text) if price_text else
                           '<span class="muted">no price published on the source page</span>'))
    specs_rows.append(_row("Memory (RAM)",
                           f"{ram} GB" if ram else '<span class="muted">not published next to the price</span>'))
    specs_rows.append(_row("vCPU",
                           str(vcpu) if vcpu else '<span class="muted">not published next to the price</span>'))
    specs_rows.append(_row("Disk",
                           f"{disk} GB" if disk else '<span class="muted">not published next to the price</span>'))
    specs_rows.append(_row("Currency", currency_code))
    specs_rows.append(_row("Read from",
                           f'<a href="{escape(offer["source_url"])}" rel="nofollow noopener" target="_blank">'
                           f'{escape(offer["source_url"])}</a>'))
    specs_rows.append(_row("Read at (UTC)", escape(offer["fetched_at"])))
    specs_table = ('<div class="table-shell"><table><tbody>' + "".join(specs_rows)
                   + "</tbody></table></div>")

    unit_rows = []
    if price_value and ram:
        unit_rows.append(_row(f"Price per GB of RAM",
                              f'<span class="price">{price_value / ram:.4f} {currency_code}</span> '
                              f'<span class="muted">= {price_value} {currency_code} ÷ {ram} GB</span>'))
    else:
        unit_rows.append(_row("Price per GB of RAM",
                              '<span class="muted">cannot be computed — the RAM figure is not published '
                              'next to this price</span>'))
    if price_value and vcpu:
        unit_rows.append(_row("Price per vCPU",
                              f'<span class="price">{price_value / vcpu:.4f} {currency_code}</span> '
                              f'<span class="muted">= {price_value} {currency_code} ÷ {vcpu} vCPU</span>'))
    else:
        unit_rows.append(_row("Price per vCPU",
                              '<span class="muted">cannot be computed — the vCPU count is not published '
                              'next to this price</span>'))
    if disk and ram:
        unit_rows.append(_row("Disk per GB of RAM",
                              f'{disk / ram:.1f} GB <span class="muted">= {disk} GB ÷ {ram} GB</span>'))
    unit_table = ('<div class="table-shell"><table><tbody>' + "".join(unit_rows)
                  + "</tbody></table></div>"
                  + '<p class="muted">Both inputs must come from the same plan block on the same page. '
                    'Where one is missing the cell says so instead of estimating it.</p>')

    siblings = [o for o in (provider_offers or []) if o.get("title") != offer.get("title")]
    if siblings:
        cmp_rows = []
        for other in sorted(siblings, key=lambda o: (o.get("price") is None, o.get("price") or 0)):
            other_price = money(other.get("price"), other.get("currency", currency))
            other_ram = other.get("ram_gb")
            per_gb = (f'{other["price"] / other_ram:.4f} {other.get("currency", "")}'
                      if other.get("price") and other_ram else '<span class="muted">-</span>')
            delta = ""
            if price_value and other.get("price"):
                diff = other["price"] - price_value
                delta = (f'<span class="muted">{diff:+.2f}</span>' if diff else
                         '<span class="muted">same</span>')
            cmp_rows.append(
                "<tr>"
                f'<td><a href="{escape(deal_page(site, other))}">{escape(other["title"])}</a></td>'
                f'<td class="price">{escape(other_price) if other_price else "not published"}</td>'
                f'<td>{escape(str(other_ram)) if other_ram else "-"}</td>'
                f'<td class="price">{per_gb}</td>'
                f'<td>{delta}</td>'
                "</tr>"
            )
        provider_table = (
            '<div class="table-shell"><table><thead><tr><th>Plan</th><th>Published price</th>'
            '<th>RAM (GB)</th><th>Per GB</th><th>vs this plan</th></tr></thead><tbody>'
            + "".join(cmp_rows) + "</tbody></table></div>"
            + f'<p class="muted">{len(siblings) + 1} {escape(offer["provider"])} plans were readable on the '
              f'source page. Differences are shown in {currency_code} without conversion.</p>'
        )
    else:
        provider_table = (
            f'<p class="muted">Only one {escape(offer["provider"])} plan could be read from the source page, '
            'so there is nothing to compare it against yet.</p>'
        )

    return render(
        template("deal.html"),
        {
            "lang": site["locale"],
            "brand": escape(site["brand"]),
            "head": head_block(meta, [schema, breadcrumb]),
            "nav": nav_block(site, []),
            "footer": footer_block(site, generated_at),
            "title": escape(title),
            "deal_title": escape(offer["title"]),
            "provider": escape(offer["provider"]),
            "provider_url": provider_page(site, offer["provider"]),
            "price": escape(price_text) if price_text else '<span class="muted">not published on the source page</span>',
            "currency": escape(currency),
            "valid_until": escape(offer.get("valid_until", "")) or '<span class="muted">not stated</span>',
            "source_url": escape(offer["source_url"]),
            "fetched_at": escape(offer["fetched_at"]),
            "offer_url": escape(offer["offer_url"]),
            "specs_table": specs_table,
            "unit_table": unit_table,
            "provider_table": provider_table,
            "base_url": escape(site["base_url"]),
            "variants_note": (
                f'The provider page currently lists {variants} different prices for this plan; the lowest is shown here.'
                if variants > 1
                else ""
            ),
        },
    )


