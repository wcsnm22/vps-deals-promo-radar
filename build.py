def _bank_questions() -> list[str]:
    """搜索补全里抓到的真人问句（data/keyword-bank.json），只取问句形态的。

    文件不存在就是还没有词库：FAQ 的问题换成数据驱动的问法，答案口径不变。
    """
    path = ROOT / "data" / "keyword-bank.json"
    if not path.exists():
        return []
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return []
    return [item["query"] for item in payload.get("queries", []) if item.get("question")][:8]


def answer_from_data(guide: dict, offers: list[dict], expanded: str | None = None) -> str:
    """第一屏的答案必须带可核对的数字，数字只能来自抓到的数据。

    ::RULE{lede 里出现的每个数都能在 offers.json 或 CSV 里复算出来}
    自动页（guides.py 生成）自己带着按主题算好的答案，直接用；
    手写页没有当日主题，这里按缺口类型给一个汇总口径的答案。
    expanded：已经用当天的数字替换过占位符的答案（见 expand_live_tokens），
    不传就退回 guides.json 里存的那份——那份里可能还留着占位符，正常路径不会走到。
    """
    if guide.get("auto") and (expanded or guide.get("answer")):
        return expanded if expanded is not None else guide["answer"]
    priced = [o for o in offers if o.get("price") is not None]
    with_ram = [o for o in priced if o.get("ram_gb")]
    ranked = sorted(with_ram, key=lambda o: o["price"] / o["ram_gb"])
    providers = len({o["provider"] for o in priced})
    gap = guide.get("gap")
    if gap == "csv":
        return (
            f"{len(priced)} tracked plans across {providers} providers; {len(with_ram)} of them publish the RAM "
            f"figure their price is quoted next to, so those rows carry a computed per-GB number. "
            f"The CSV hands over the table itself."
        )
    if gap == "unitprice" and ranked:
        best = ranked[0]
        return (
            f"Cheapest RAM per unit today is {best['provider']} {best['title']} at "
            f"{best['price'] / best['ram_gb']:.4f} {best.get('currency', '')} per GB "
            f"({best['price']} {best.get('currency', '')} / {best['ram_gb']} GB) — computed only from numbers the "
            f"provider published. {len(with_ram)} of {len(priced)} priced plans can be ranked at all."
        )
    if gap == "steps":
        cheapest = min(priced, key=lambda o: o["price"]) if priced else None
        cheapest_text = money(cheapest["price"], cheapest.get("currency", "USD")) if cheapest else "n/a"
        return (
            f"{len(priced)} tracked plans, cheapest at {cheapest_text} per month "
            f"({cheapest['provider']} {cheapest['title']}). Eight numbered steps from picking the plan to "
            f"logging in, each sourced to provider documentation."
            if cheapest
            else "No tracked plan currently publishes a price, so no step cost can be quoted."
        )
    return guide["answer"]


def _chart_html(*names: str, alt: str) -> str:
    """套图插进页面：文件不存在就什么都不插，绝不插一条坏链接。"""
    blocks = []
    for name in names:
        if not (SITE_DIR / "assets" / name).exists():
            continue
        blocks.append(
            f'<p><img src="/assets/{escape(name)}" alt="{escape(alt)}" '
            f'width="760" height="auto" loading="lazy" decoding="async" '
            f'style="max-width:100%;height:auto;border-radius:10px"></p>'
        )
    return "".join(blocks)


def related_guides_html(site: dict, guide: dict, guides: list[dict], limit: int = 6) -> str:
    """同题材互链：本页 → 指南索引 → 今天那篇 + 同一缺口的前几篇 + 另外两个缺口的入口。

    14 个指南页原来只靠 sitemap 串起来，页面上彼此不指路。这里把最近的几篇连起来，
    让读者和爬虫都能顺着走。
    """
    others = [row for row in guides if row.get("slug") != guide.get("slug")]
    same_gap = [row for row in others if row.get("gap") == guide.get("gap")][-3:]
    by_date = sorted(others, key=lambda row: row.get("published", ""), reverse=True)[:2]
    picks: list[dict] = []
    for row in same_gap + by_date:
        if row not in picks:
            picks.append(row)
    items = [
        f'<li><a href="{escape(guide_page(site, row))}">{escape(row["title"])}</a></li>'
        for row in picks[:limit]
    ]
    items.append(f'<li><a href="{escape(guides_url(site))}">All guides ({len(guides)})</a></li>')
    items.append(
        f'<li><a href="{escape(site["base_url"])}/downloads/unit-price.csv">Download the price table (CSV)</a></li>'
    )
    return '<h2>More on this site</h2><ul>' + "".join(items) + "</ul>"


def updated_line(guide: dict, generated_at: str) -> str:
    """人眼可见的更新时间。

    对标的三家都把"什么时候更新的"写在正文里（lowendbox 同一页写了三个月份），
    我们原来只在 HTML head 里有日期，读者看不到。这里照实写两个日期：这篇什么时候发的、
    这些数字什么时候重新读的。
    """
    published = (guide.get("published") or generated_at)[:10]
    return (
        f'<p class="muted">Published {escape(published)} · prices last read from the providers '
        f'{escape(generated_at)} (UTC).</p>'
    )


def guide_focus(guide: dict, offers: list[dict]) -> str | None:
    """这篇指南的正文只排哪一家；排全站就返回 None。

    没在 guides.json 里加字段，而是从标题里认出厂商名：自动生成的标题把主题厂商写在标题里
    （csv 页是 "- <厂商> plans"、unitprice 页是 ": <厂商> -"、steps 页是 "steps: <厂商> plan"），
    手写页和 queue 页标题里没有厂商名。这样不用改数据文件，老页面也照样认得出。

    口径原则：FAQ 只答本页表格里那批行，认不出厂商的页面才用全站口径。
    """
    names = {o["provider"] for o in offers}
    title = guide.get("title", "")
    hits = [name for name in names if name in title]
    return hits[0] if len(hits) == 1 else None


# queue 页的标题形状固定（guides.py 的 build_queue_entry 生成），冒号后面是队列里的词，
# 标题本身说明了这一页排的是哪一批行：按磁盘单价排 / 按内存单价排 / 按月费排。
_QUEUE_TITLE_FIELDS = (
    ("Cheapest VPS disk per TB:", "disk_gb"),
    ("Cheapest VPS RAM per GB:", "ram_gb"),
    ("Cheapest tracked VPS plans:", None),
)


def guide_scope_offers(guide: dict, offers: list[dict]) -> list[dict]:
    """这一页正文真正排的那批行——FAQ 就答这批，不答全站。

    两种页面各有各的口径：厂商页只排一家（标题里有厂商名），queue 页按标题里写的那个维度
    筛过一遍（只排公布了硬盘/内存的那批）。都不是的（手写常青页）才用全站口径——
    那几页本来就横着看全站数据，答全站才是对的。这里只做筛选，不新增任何数字来源。
    """
    title = guide.get("title", "")
    for prefix, field in _QUEUE_TITLE_FIELDS:
        if title.startswith(prefix):
            if field is None:
                return [o for o in offers if o.get("price") is not None]
            return [o for o in offers if o.get("price") is not None and o.get(field)]
    focus = guide_focus(guide, offers)
    if focus:
        return [o for o in offers if o["provider"] == focus]
    return offers


# 手写常青页横着看全站数据（三页同行集），给各自一句范围说法，答案才不会一字不差。
_HANDWRITTEN_SCOPE = {
    "vps-comparison-table-csv": "in the downloadable comparison table",
    "how-to-buy-and-connect-a-cheap-vps": "across the plans these steps cover",
    "how-vps-pricing-works": "across the plans used in this explainer",
}


def guide_scope_phrase(guide: dict, offers: list[dict]) -> str:
    """这一页的范围，写成一个能接在句子任何位置的状语，写进 FAQ 答案里。

    必须能区分同类的两页，否则两页的 FAQ 又会一字不差：
      - queue 页只按维度筛行，两页"按月费排"的 queue 页行集是一样的 → 带上队列里那个词；
      - 自动页按厂商轮换，同一家会隔几天再轮到一次（IONOS 的 csv 页来过两次、
        Hostwinds 的单价页来过两次），行集也一样 → 带上这一页自己的发布日期。
        说"这一页"而不是"这一天的价格"：页面上排的就是这一页的表，价格是构建时抓的，
        不该暗示数字取自那一天。
    """
    title = guide.get("title", "")
    for prefix, _ in _QUEUE_TITLE_FIELDS:
        if title.startswith(prefix):
            term = title[len(prefix):].split(" - ", 1)[0].strip()
            return f'in the "{term}" shortlist' if term else "in this shortlist"
    focus = guide_focus(guide, offers)
    if not focus:
        return _HANDWRITTEN_SCOPE.get(guide.get("slug", ""), "among the tracked plans")
    snapshot = (guide.get("published") or "")[:10]
    if guide.get("auto") and snapshot:
        return f"on the {snapshot} {focus} page"
    return f"on the {focus} plan list"


def build_guide(
    site: dict, guide: dict, offers: list[dict], providers: list[dict], generated_at: str,
    guides: list[dict] | None = None,
) -> str:
    # 每一篇只补一个缺口，正文在 data/guides.json 里给定（自动页由 guides.py 生成）。
    # 这里不再按 gap 现编内容，避免出现"同一份数据被渲染成两种说法"。
    # 正文里全站口径的数字是占位符，按**今天**的抓取结果填（见 live_counts），
    # 否则页面上的表格行数和同一页 FAQ / CSV / 页脚日期会各说各话。
    body = expand_live_tokens(guide.get("body_html", ""), offers)
    answer = expand_live_tokens(guide.get("answer", ""), offers)
    if re.search(r'href="[^"]*(/deal/|source_url)', body):
        raise SystemExit(f'guide {guide["slug"]} must not link to per-offer pages; bodies stay data-free')
    if not body:
        raise SystemExit(f'guide {guide["slug"]} has no body_html; refusing to publish an empty page')

    title = f'{guide["title"]} — {site["title"]}'
    meta = {
        "canonical": guide_page(site, guide),
        "locale": site["locale"],
        "title": title,
        "description": answer,
        "brand": site["brand"],
        "og_type": "article",
        "og_image": site["og_image"],
    }
    article = {
        "@context": "https://schema.org",
        "@type": "TechArticle",
        "headline": guide["title"],
        "description": answer,
        "url": guide_page(site, guide),
        # 自动页自己有发布日期：用它，别用构建时间——否则每重建一次"发布日"就变一次。
        "datePublished": (guide.get("published") or generated_at)[:10],
        "dateModified": generated_at[:10],
        "isPartOf": {"@type": "WebSite", "name": site["title"], "url": home_url(site)},
    }
    breadcrumb = {
        "@context": "https://schema.org",
        "@type": "BreadcrumbList",
        "itemListElement": [
            {"@type": "ListItem", "position": 1, "name": site["title"], "item": home_url(site)},
            {"@type": "ListItem", "position": 2, "name": "Guides", "item": guides_url(site)},
            {"@type": "ListItem", "position": 3, "name": guide["title"], "item": guide_page(site, guide)},
        ],
    }
    sources = "".join(
        f'<li><a href="{escape(item["url"])}" rel="nofollow noopener" target="_blank">{escape(item["label"])}</a>'
        f' — read {escape(generated_at)}</li>'
        for item in guide.get("sources", [])
    )
    # T4：一问一答。问题来自搜索补全里的真人问句，答案全部由今天抓到的数字现算。
    # FAQ 只答**这一页表格里排的那批行**（见 guide_scope_offers / guide_scope_phrase）：
    # 厂商页只答那一家，queue 页只答标题里那个维度筛出来的那批。
    # 原来这里传的是全站 offers，于是 19 个指南页的 5 问 5 答一字不差，
    # 可见文本和 FAQPage 两份都一样，页面之间互相判成重复。
    faqs = frequently_asked(
        guide_scope_offers(guide, offers),
        _bank_questions(),
        guide_scope_phrase(guide, offers),
    )
    faq_html = ""
    extra_jsonld = [article, breadcrumb]
    # T5 套图：单价页插"每 GB 最便宜"的图，主题厂商有专属图就一起插。
    chart_html = ""
    if guide.get("gap") == "unitprice":
        # 标题形如 "Cheapest VPS per GB of RAM: Hostwinds - ..."，冒号后面就是主题厂商。
        focus = guide.get("title", "").split(":", 1)[1].split("-")[0].strip() if ":" in guide.get("title", "") else ""
        chart_html = _chart_html(
            "per-gb-cheapest.svg",
            f"per-gb-{slugify(focus)}.svg" if focus else "",
            alt=f'Monthly price per GB of RAM, computed from published prices ({guide["title"]})',
        )
        chart_html = chart_html + _chart_html(
            f"monthly-vs-ram-{slugify(focus)}.svg" if focus else "",
            alt=f'What the monthly fee buys at {focus}',
        )
    if faqs:
        rows = "".join(
            f'<h3>{escape(item["question"])}</h3><p>{escape(item["answer"])}</p>'
            + (f'<p class="muted">asked as: {escape(item["asked_as"])}</p>' if item.get("asked_as") else "")
            for item in faqs
        )
        faq_html = f'<h2>Questions this page answers</h2>{rows}'
        extra_jsonld.append({
            "@context": "https://schema.org",
            "@type": "FAQPage",
            "mainEntity": [
                {"@type": "Question", "name": item["question"],
                 "acceptedAnswer": {"@type": "Answer", "text": item["answer"]}}
                for item in faqs
            ],
        })
    return render(
        template("guide.html"),
        {
            "lang": site["locale"],
            "brand": escape(site["brand"]),
            "head": head_block(meta, extra_jsonld),
            "nav": nav_block(site, providers),
            "footer": footer_block(site, generated_at),
            "title": escape(title),
            "h1": escape(guide["title"]),
            "answer": f'<p class="lede">{escape(answer_from_data(guide, offers, answer))}</p>' + chart_html,
            "body": body + faq_html + related_guides_html(site, guide, guides or []),
            "updated": updated_line(guide, generated_at),
            "gap_note": escape(guide["gap_note"]),
            "sources": f'<h2>Sources</h2><ul>{sources}</ul>' if sources else "",
        },
    )


